/** Section keys shown in the Project Materials Hub (8 sections). */
export type MaterialSectionKey =
  | 'story'
  | 'characters'
  | 'character_refs'
  | 'image_prompts'
  | 'video_prompts'
  | 'production_settings'
  | 'generated_images'
  | 'generated_videos';

export type PlatformChoice =
  | 'youtube_movie'
  | 'youtube_shorts'
  | 'tiktok'
  | 'instagram_reels'
  | 'custom';

export type AspectRatio = '16:9' | '9:16' | '1:1' | '4:3' | '3:4';

export type SupportedResolution = '480p' | '720p' | '1080p';

export type GenerateTargetType = 'image' | 'video' | 'image_and_video';

export interface StorySectionData {
  rawText: string;
  filename?: string;
  savedAt?: string;
  locked: boolean;
  lockedAt?: string;
}

export interface CharacterRefSlot {
  prompt: string;
  imageUrl?: string;
  filename?: string;
  source?: 'uploaded' | 'sample_asset' | 'cloud_generated';
  uploadedAt?: string;
  savedAt?: string;
  locked?: boolean;
  lockedAt?: string;
}

export type CharacterRefSlotKey = 'face' | 'front' | 'side' | 'back';

export interface CharacterCard {
  id: string;
  // A. Character Information (Name, Age, Gender, Appearance, Clothing, Personality, Walking style, Body language)
  nameAndDetails: string;
  infoFilename?: string;
  // B. Face Reference, C. Front Body Reference, D. Side Body Reference, E. Back Body Reference
  references: {
    face: CharacterRefSlot;
    front: CharacterRefSlot;
    side: CharacterRefSlot;
    back: CharacterRefSlot;
  };
  savedAt?: string;
  locked: boolean;
  lockedAt?: string;
}

export type AssetSource = 'cloud_generated' | 'uploaded' | 'sample_asset';

/** One real output file for a shot (AI generated by the backend, or uploaded by the user). */
export interface ShotAssetCandidate {
  id: string;
  url: string;
  source: AssetSource;
  createdAt: string;
  /** Prompt text the asset was produced from (to detect stale outputs). */
  fromPrompt: string;
  filename?: string;
  /** Backend job that produced this version (AI video), used to recover finished jobs. */
  jobId?: string;
}

export interface ParsedPromptEntry {
  id: string;
  sceneId: string;
  shotId: string;
  orderIndex: number;
  promptText: string;
  linkedImageKey?: string; // e.g., "S01-SH01"
  /** URL of the currently selected candidate (used for export and image-to-video). */
  generatedUrl?: string;
  assetSource?: AssetSource;
  candidates?: ShotAssetCandidate[];
  selectedCandidateId?: string;
  status: 'waiting' | 'generating' | 'completed' | 'failed';
  errorMessage?: string;
  /** Backend video job id while a video is being generated. */
  backendJobId?: string;
  /** Id of the most recent backend job for this shot (kept after failure so a retry can link to it). */
  lastJobId?: string;
}

/** Save / Lock state for the Generated Images and Generated Videos sections. */
export interface OutputSectionState {
  savedAt?: string;
  locked: boolean;
  lockedAt?: string;
  /** Scene-Shot keys + selected candidate ids at the moment of Save. */
  savedSelection?: Record<string, string>;
}

export interface PromptSectionData {
  rawText: string;
  filename?: string;
  savedAt?: string;
  locked: boolean;
  lockedAt?: string;
  parsedItems: ParsedPromptEntry[];
}

export interface ModelCapabilityProfile {
  id: string;
  label: string;
  providerNote: string;
  supportedResolutions: SupportedResolution[];
  supportedDurationsSec: number[];
  maxGenerationOrder: 1 | 2 | 3 | 4;
}

export interface ProductionSettings {
  generateType: GenerateTargetType;
  platform: PlatformChoice;
  customPlatformLabel: string;
  aspectRatio: AspectRatio;
  resolution: SupportedResolution;
  imageQuantity: 1 | 2 | 3 | 4;
  videoQuantity: 1 | 2 | 3 | 4;
  generationOrder: 1 | 2 | 3 | 4;
  videoDurationSec: number;
  modelProfileId: string;
  savedAt?: string;
  locked: boolean;
  lockedAt?: string;
}

export interface CloudBackendSettings {
  backendUrl: string;
  gcpProjectId: string;
  gcpRegion: string;
  gcsBucket: string;
  /** Optional shared token if the server sets STUDIO_ACCESS_TOKEN (not an AI API key). */
  accessToken?: string;
  status: 'not_configured' | 'connected' | 'unreachable';
  geminiConfigured?: boolean;
  ffmpegAvailable?: boolean;
  /** From /health: 'google' when the server requires Google sign-in. */
  authMode?: 'google' | 'none';
  googleClientId?: string | null;
  /** Firestore project sync available (server side). */
  cloudSync?: boolean;
  storage?: 'gcs' | 'local-disk';
  serverWarnings?: string[];
  lastError?: string;
  lastCheckedAt?: string;
}

